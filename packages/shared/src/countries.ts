export function dialCode(code: string) {
  return DIAL[code] ?? '';
}

/** The flag emoji for a country code, from its two regional-indicator letters. */
export function flag(code: string) {
  return String.fromCodePoint(...[...code.toUpperCase()].map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65));
}

export function countryName(code: string) {
  return COUNTRIES.find(([value]) => value === code)?.[1] ?? code;
}
